# الكلمات اللي بتقتل الهوك — لو لقيناها في نص المحتوى ما نستخدمهاش
KILLERS = re.compile(
    r"^(?:نور|مرحبا|أهلا|السلام عليكم|في الفيديو ده|النهاردة هن|هنتكلم عن|"
    r"موضوعنا|تعالوا|يلا بينا|بسم الله نبدأ)\b", re.UNICODE)

STOPWORDS = {
    "من", "في", "على", "عن", "إلى", "الى", "أن", "ان", "إن", "ما", "لا",
    "هو", "هي", "ده", "دي", "اللي", "الذي", "التي", "كان", "كانت", "ثم",
    "كل", "بعد", "قبل", "بين", "حتى", "لو", "أو", "او", "و", "ب", "ل",
    "the", "a", "an", "of", "to", "and", "is", "are", "was",
}


def _seed(*parts: str) -> int:
    return int(hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()[:12], 16)


def keyword(text: str, limit: int = 4) -> str:
    """يستخرج أقوى كلمة/عبارة مفتاحية من النص — اللي الهوك يتكوّن عليها."""
    words = re.findall(r"[\u0621-\u064A\u0660-\u0669\w]{3,}", str(text or ""))
    ranked = [w for w in words if w not in STOPWORDS]
    if not ranked:
        return "الكلام ده"
    # نفضّل العبارة من 2 كلمة لو موجودة (أدق من كلمة لوحدها)
    if len(ranked) >= 2:
        return f"{ranked[0]} {ranked[1]}"
    return ranked[0]


def is_weak(hook: str) -> bool:
    """هل الهوك ضعيف؟ (مقدمة مملة · قصير أوي · طويل أوي · بلا معنى)"""
    h = str(hook or "").strip()
    if len(h) < 8 or len(h) > 95:
        return True
    if KILLERS.match(h):
        return True
    if h.count(" ") < 2:          # جملة من كلمتين بتبقى باهتة
        return True
    return False


def _fill(template: str, x: str) -> str:
    return template.replace("{x}", x).replace("  ", " ").strip()


def subject_class(x: str) -> str:
    """يصنّف الكلمة المفتاحية: «سلبي» (وجع) · «إيجابي» (خير) · «شيء» (موضوع).

    الفايدة: قوالب المعاناة ما تتلبّسش على كلمة إيجابية، والعكس.
    """
    s = str(x or "")
    if any(w in s for w in STATE_NEG):
        return "سلبي"
    if any(w in s for w in STATE_POS):
        return "إيجابي"
    return "شيء"


def template_ok(template: str, cls: str, subject: str = "") -> bool:
    """هل القالب ده ينفع مع نوع الكلمة؟ (بوابة منع الجمل المكسورة)

    بوابتين:
      1) نوع الكلمة: سلبي/إيجابي/شيء.
      2) طول الكلمة: كلمة واحدة ما تنفعش تكون **فاعل** جملة
         («علم مش اللي بيقولوه» مكسورة) — لكن تنفع **مجرورة**
         («معلومة تغيّر نظرتك لـعلم» سليمة).
    """
    if cls not in TEMPLATE_NEEDS.get(template, _ALLOW_MOST):
        return False
    # كلمة واحدة ما تصلحش تبقى فاعل جملة، لازم تبقى **مجرورة** (بعد حرف جر).
    if " " not in str(subject or "").strip():
        if not re.search(r"(?:عن|إلى|على|مع|في|من|لـ|ل|بـ|ب)\s?\{x\}", template):
            return False
    return True


def _from_text(text: str) -> list[str]:
    """هوكات من **كلام الحلقة نفسه** — أصدق وأقوى من قالب جاهز.

    الفكرة: أقوى جملة في المحتوى بتتحوّل سؤال. الجملة بتبقى من كلام
    المصنع أصلًا، فمستحيل تطلع مكسورة أو غريبة.
    """
    out: list[str] = []
    try:
        raw = re.split(r"(?<=[.!؟?])\s+|\n+", str(text or ""))
    except Exception:
        return out
    scored: list[tuple[int, str]] = []
    for pos, s in enumerate(raw):
        s = s.strip().strip(".،؛")
        if not s or len(s) < 12 or len(s) > 78:
            continue
        if KILLERS.match(s) or is_weak(s):
            continue
        words = len(s.split())
        # نفضّل جمل قصيرة واضحة (٣–٩ كلمات) — دي اللي بتعلق في الدماغ
        score = 100 - abs(words - 6) * 6 - abs(len(s) - 34)
        # وميل بسيط لجمل البداية: الهوك من أول الفيديو أحسن من نهاية الفيديو
        if pos == 0:
            score += 10
        elif pos == 1:
            score += 5
        if any(k in s for k in ("مش", "ما ", "لا ", "لكن", "بس ", "أكتر", "أقل")):
            score += 12                      # جملة فيها مفارقة = أقوى
        scored.append((score, s))
    scored.sort(reverse=True)
    for _, s in scored[:4]:
        s = s.strip().strip("«»\"'").strip()
        if not s:
            continue
        out.append(f"«{s}» — تعرف ليه؟")
        out.append(f"{s}؟")
    return out


def candidates(*, text: str = "", topic: str = "", kind: str = "",
               surah: str = "", who: str = "") -> Iterator[tuple[str, str]]:
    """يولّد هوكات محتملة مرتّبة. بيرجّع (الهوك, النمط)."""
    subject = topic.strip() or keyword(text) or surah or who or "الكلام ده"

    # نختار الأنماط المناسبة للنوع الأول
    order = {
        "hadith": ("تدبر", "سؤال", "معرفة", "مفارقة"),
        "ayah": ("تدبر", "وجدان", "سؤال", "مفارقة"),
        "quran": ("تدبر", "وجدان", "سؤال"),
        "story": ("سؤال", "وجدان", "مفارقة", "مباشر"),
        "quiz": ("سؤال", "رقم", "معرفة"),
        "dua": ("وجدان", "تدبر", "مباشر"),
        "life": ("مباشر", "مفارقة", "وجدان", "خفة"),
        "science": ("مفارقة", "سؤال", "معرفة", "رقم"),
        "qfacts": ("معرفة", "سؤال", "رقم"),
        "proverb": ("خفة", "مفارقة", "مباشر"),
    }.get(str(kind or ""), ("سؤال", "مفارقة", "معرفة", "وجدان", "مباشر"))

    seen: set[str] = set()
    cls = subject_class(subject)

    # 1) لوكات **من كلام الحلقة نفسه** — بتتقدم لأنها أصدق وأمنع للكسر
    for got in _from_text(text):
        if got not in seen:
            seen.add(got)
            yield got, "من_المحتوى"

    # 2) القوالب الجاهزة — بس اللي ينفع مع نوع الكلمة
    for name in order:
        for tpl in TEMPLATES.get(name, ()):  # type: ignore[arg-type]
            if not template_ok(tpl, cls, subject):
                continue
            got = _fill(tpl, subject)
            if got and got not in seen:
                seen.add(got)
                yield got, name


def pick(*, text: str = "", topic: str = "", kind: str = "",
         surah: str = "", who: str = "", episode_id: str = "",
         spoken_fallback: str = "") -> dict:
    """يختار الهوك الأمثل للحلقة.

    بيرجّع:
        {"hook": "...", "style": "...", "subject": "...", "source": "مولّد"|"أصلي", "variants": [...]}

    القاعدة: لو الهوك الأصلي (اللي جاي من المحتوى) قوي، بنحترمه —
    إحنا بنضيف، مش بنستبدل.
    """
    seed = _seed(episode_id, kind, topic, surah)
    subject = topic.strip() or keyword(text) or surah or who or "الكلام ده"
    made = list(candidates(text=text, topic=topic, kind=kind, surah=surah, who=who))

    if not made:
        return {
            "hook": spoken_fallback or f"اسمع {subject}.",
            "style": "أصلي", "subject": subject, "source": "أصلي", "variants": [],
        }

    # ترتيب موزون: أسلوب أقوى = فرصة أكبر، وبذرة الحلقة بتحدد الاختيار
    pool: list[tuple[str, str]] = []
    for hook, style in made:
        pool.extend([(hook, style)] * WEIGHTS.get(style, 1))
    chosen_hook, chosen_style = pool[seed % len(pool)]

    # لو الهوك الأصلي قوي، نسيبه هو وناخده كـالأصلي
    orig = str(spoken_fallback or "").strip()
    if orig and not is_weak(orig):
        return {
            "hook": orig, "style": "أصلي", "subject": subject,
            "source": "أصلي",
            "variants": [h for h, _ in made[:4]],
        }

    return {
        "hook": chosen_hook, "style": chosen_style, "subject": subject,
        "source": "مولّد",
        "variants": [h for h, _ in made[:6] if h != chosen_hook],
    }


def hook_line(hook: str, style: str = "") -> str:
    """يجهّز الهوك للسرد — علامة ترقيم بتخلي edge-tts يوقّف وقفة قصيرة."""
    h = str(hook or "").strip().rstrip(".")
    if not h:
        return ""
    # وقفة قصيرة بعد الهوك = يفرض على المستمع يسمعه
    return h + "."


def apply(item: dict, *, force: bool = False) -> dict:
    """يطبّق محرّك الهوك على عنصر المكتبة. آمن: أي فشل = العنصر زي ما هو."""
    try:
        if str(__import__("os").environ.get("NOOR_PRO_HOOKS", "1")) == "0" and not force:
            return item
        kind = str(item.get("kind") or item.get("plan_kind") or "")
        got = pick(
            text=str(item.get("spoken") or item.get("text") or ""),
            topic=str(item.get("field") or item.get("theme") or ""),
            kind=kind,
            surah=str(item.get("surah_name") or item.get("surah") or ""),
            who=str(item.get("who") or ""),
            episode_id=str(item.get("id") or ""),
            spoken_fallback=str(item.get("hook") or ""),
        )
        out = dict(item)
        out["hook"] = got["hook"]
        out["hook_style"] = got["style"]
        out["hook_source"] = got["source"]
        out["hook_variants"] = got["variants"][:4]
        return out
    except Exception as exc:  # noqa: BLE001
        print(f"[pro.hooks] اتخطى: {type(exc).__name__}", flush=True)
        return item
