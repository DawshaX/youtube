"""فهرس الفروع — عنوان محسوب، مش قائمة فاضية تتسخن المصنع.

المحاور من تصنيفات يوتيوب الواسعة، وشجرة علوم الدين، ومهارات الحياة.
كل فرع عنوان حقيقي (عيلة × مجال × وقت × مخاطب × شكل × يوم × طول).
البوت يقدر يوصل لأي عنوان. النشر لا يسحب الفرع إلا إذا وراه سيناريو جاهز.
"""
from __future__ import annotations

# ٨ عيلات محتوى. الشكل محور مستقل عشان ما يبقاش موضوع.
FAMILIES = (
    "دين مقدس", "سنة وذكر", "قصص ونور", "روح وسكينة",
    "علم وإفادة", "حياة نافعة", "فهم النفس", "خير عام",
)
MOMENTS = ("فجر", "ضحى", "ظهر", "عصر", "مغرب", "عشاء", "ليل", "سحر")
AUDIENCES = ("نفس", "أهل", "جار", "ضيف", "غريب", "طريق")
SHAPES = (
    "سينما", "ذهب", "حبر", "زمرد", "رمل", "قمر",
    "فصل", "ضباب", "وثائقي", "شريط", "نافذة", "هادي",
)
DAYS = ("اثنين", "ثلاثاء", "أربعاء", "خميس", "جمعة", "سبت", "أحد")
LENGTHS = (8, 20, 45, 90, 175)
DOMAINS = (
    "قرآن مصدر", "تدبر مصدر", "حديث مصدر", "أذكار مصدر", "دعاء مصدر",
    "قصص أنبياء مصدر", "أسماء الله مصدر", "مواقيت مصدر",
    "ماء", "كلام", "بيت", "ناس", "طريق", "طبيعة", "عمل", "نفس", "نعمة", "وقت",
    "لغة", "حرفة", "صحة هادية", "رفق", "سؤال", "مثل", "ترتيب", "مشي",
    "شكر", "ستر", "يسر", "أمانة", "صبر", "عفو", "لطف", "إنصات",
    "علم خلق", "رقم في الطبيعة", "موسم", "حديقة", "سوق صادق", "ضيف",
    "صفحة", "بداية", "خاتمة",
)

AXES = (FAMILIES, DOMAINS, MOMENTS, AUDIENCES, SHAPES, DAYS, LENGTHS)


def branch_count() -> int:
    n = 1
    for axis in AXES:
        n *= len(axis)
    return n


def branch_at(i: int) -> dict:
    """يفك رقم الفرع إلى عنوان مفهوم. لا يصنع فيديو."""
    if i < 0 or i >= branch_count():
        raise IndexError(i)
    parts = []
    keys = ("family", "domain", "moment", "audience", "shape", "day", "length")
    x = i
    for axis, key in zip(AXES, keys):
        parts.append((key, axis[x % len(axis)]))
        x //= len(axis)
    data = dict(parts)
    data["id"] = f"br-{i:07d}"
    data["ar"] = (
        f"{data['family']} · {data['domain']} · {data['moment']} · "
        f"{data['audience']} · {data['shape']} · {data['day']} · {data['length']}ث"
    )
    data["publishable"] = False
    data["note"] = "عنوان في الفهرس. ينزل فيديو فقط لو وراه سيناريو جاهز ومصدره مسموح."
    return data
