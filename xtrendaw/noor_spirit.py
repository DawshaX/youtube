CATS = tuple(THEMES)


def make(theme: str | None = None, index: int | None = None) -> dict | None:
    """عنصر روحاني (ثيم + سطر) — حتمي، بلا تكرار متقارب."""
    import time
    turns = list(CATS)
    t = theme if theme in THEMES else turns[int(time.time() // 1800) % len(turns)]
    data = THEMES[t]
    lines = data["lines"]
    i = int(index if index is not None else (time.time() // 1800) % len(lines))
    line = lines[i % len(lines)]
    return {
        "id": f"spirit-{t}-{i % len(lines)}",
        "kind": "spirit",
        "theme": t,
        "hook": data["hook"],
        "lines": [line],
        "outro": data["outro"],
        "scenes": data["scenes"],
        "source": "🌿 نور — كلمة تطمئن القلب (بلا موسيقى)",
    }


def series() -> list[dict]:
    """كل عناصر الروحانيات (للخطة الأبدية) — ثيم × سطر."""
    out = []
    for t, d in THEMES.items():
        for i in range(len(d["lines"])):
            it = make(t, i)
            if it:
                out.append(it)
    return out
