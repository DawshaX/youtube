_TABLES = {"mujiza": MUJIZA, "hamd": HAMD, "nasr": NASR}
_THEME = {"mujiza": "معجزات", "hamd": "حمد", "nasr": "نصر"}


def series(kind: str) -> list[tuple[str, dict]]:
    rows = _TABLES.get(kind) or []
    out = []
    for i, (who, surah, ayah, ayah_to, hook) in enumerate(rows, 1):
        key = f"{kind[:2]}-{surah}-{ayah}"
        out.append((key, {
            "kind": kind,
            "who": who,
            "surah": surah,
            "ayah": ayah,
            "ayah_to": ayah_to if ayah_to != ayah else None,
            "hook": hook,
            "theme": _THEME[kind],
            "plan": kind,
            "series": f"سلسلة { _THEME[kind] } ({i}/{len(rows)})",
            "scenes": None,  # noor_grid.SCENES يتسابك وقت الرندر لو فاضي
        }))
    return out
