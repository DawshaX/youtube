SHAPES = ("bl", "br", "tl", "tr", "none")
YS = (0.30, 0.38, 0.46, 0.56, 0.64)
HOSTS = ("نور", "سَكينة", "أمل", "حَكيم", "راوي", "فارس")


def _items() -> list[dict]:
    out = []
    i = 0
    for cluster in CLUSTERS:
        for noun in cluster["nouns"]:
            for act_i, act in enumerate(cluster["acts"]):
                deed = act.format(n=noun)
                out.append({
                    "i": i,
                    "cluster": cluster["id"],
                    "cluster_ar": cluster["ar"],
                    "noun": noun,
                    "deed": deed,
                    "scene": cluster["scene"],
                    "act_i": act_i,
                })
                i += 1
    return out


def shape_for(i: int) -> dict:
    """تركيبة شكل لا تتكرر داخل الألف. أساس مختلط، مش باقي قسمة واحد."""
    n = i
    layout = n % 15; n //= 15
    plate = n % 5; n //= 5
    y = n % 5; n //= 5
    step = n % 3; n //= 3
    host = n % 6; n //= 6
    size = n % 5
    return {
        "layout": layout,
        "plate": SHAPES[plate],
        "y": YS[y],
        "step": 2 + step,
        "host_i": host,
        "size": 68 + size * 6,
    }


def kinds() -> list[dict]:
    out = []
    for raw in _items():
        i = raw["i"]
        rec = shape_for(i)
        noun = raw["noun"]
        deed = raw["deed"]
        out.append({
            "id": f"sanad-{i:04d}-{raw['cluster']}",
            "slug": f"{raw['cluster']}-{i:04d}",
            "name": noun,
            "kind": "spirit",
            "plan_kind": "sanad",
            "theme": raw["cluster_ar"],
            "hook": deed,
            "lines": [deed + ". " + WHY[raw["act_i"]]],
            "outro": f"لو نفعك الأمر مع {noun}، طبّقه اليوم بهدوء.",
            "scenes": [raw["scene"], "soft natural light no people", "calm wide sky no faces"],
            "source": "نور — سيناريو خير من المصنع، ليس اقتباسًا",
            "variety": 2000 + i,
            "recipe": rec,
            "branch_family": "spirit",
        })
    return out


def cards() -> list[tuple[str, dict]]:
    return [(k["id"], k) for k in kinds()]


def signatures() -> list[tuple]:
    out = []
    for i in range(len(_items())):
        r = shape_for(i)
        out.append((r["layout"], r["plate"], r["y"], r["step"], r["host_i"], r["size"]))
    return out
